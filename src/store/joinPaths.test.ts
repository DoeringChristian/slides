import { afterEach, expect, it } from 'vitest';
import { usePresentationStore as store } from './presentationStore';
import { createPresentation, createShapeElement, createTextElement } from '../utils/model/slideFactory';
import { jsonToYDoc, yDocToJson } from '../collab/ySchema';
import { setActiveDoc } from '../collab/yDocAdapter';
import { createUndoManagerFor, setActiveUndoManager } from '../collab/activeUndo';
import { pathPointsInSlide } from '../utils/paths/pathEditing';
afterEach(()=>{setActiveUndoManager(null);setActiveDoc(null);});
it.each([false,true])('join stays on this slide and undoes atomically (collab=%s)',collab=>{
  const p=createPresentation(),slide=p.slides[p.slideOrder[0]];
  const a=createShapeElement('path',{id:'a',x:0,y:0,points:[0,0,100,0],width:100,height:1,stroke:'#ff0000'});
  const b=createShapeElement('path',{id:'b',x:100,y:0,points:[0,0,100,0],width:100,height:1});
  const label=createTextElement({id:'label',containerId:'b',x:120,y:10});
  slide.elements={a,b,label};slide.elementOrder=['a','b','label'];
  p.slides.other={...structuredClone(slide),id:'other'};p.slideOrder.push('other');
  store.setState({presentation:structuredClone(p)});store.temporal.getState().clear();
  const doc=collab?jsonToYDoc(p):null;setActiveDoc(doc);
  const undo=doc?createUndoManagerFor(doc):null;setActiveUndoManager(undo);
  const read=()=>doc?yDocToJson(doc):store.getState().presentation;
  expect(store.getState().joinPaths(slide.id,['a','b'])).toBe('a');
  const joined=structuredClone(read());const result=joined.slides[slide.id].elements.a;
  expect(result.type).toBe('shape');if(result.type!=='shape')throw Error();
  expect(pathPointsInSlide(result)).toEqual([0,0,100,0,200,0]);expect(result.stroke).toBe('#ff0000');
  expect(joined.slides[slide.id].elements.b.visible).toBe(false);
  expect(joined.slides[slide.id].elements.label).toEqual({...label,containerId:null});
  expect(joined.slides.other).toEqual(p.slides.other);
  const restored=yDocToJson(jsonToYDoc(joined));
  expect(restored.slides[slide.id].elements.a).toEqual(result);
  expect(restored.slides[slide.id].elements.b.visible).toBe(false);
  expect((restored.slides[slide.id].elements.label as typeof label).containerId ?? null).toBe(null);
  if(undo)undo.undo();else store.temporal.getState().undo();expect(read().slides).toEqual(p.slides);
  if(undo)undo.redo();else store.temporal.getState().redo();expect(read().slides).toEqual(joined.slides);
});
