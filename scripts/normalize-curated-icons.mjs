// Reviewed paint regions: details stay strokes; nested closed details cut holes.
const regions = {house:[[1]],search:[[1]],user:[[1]],users:[[3]],settings:[[0,1]],bell:[[1]],mail:[[1]],phone:[[0]],calendar:[[2]],clock:[[0]],heart:[[0]],star:[[0]],cloud:[[0]],sun:[[0]],moon:[[0]],camera:[[0,1]],image:[[0,1]],'map-pin':[[0,1]]};
const norm = p => p.map(v => Number((v / 24).toFixed(12)));
function path(d, id) {
  const tokens = d.match(/[a-zA-Z]|[-+]?(?:\d*\.\d+|\d+\.?\d*)(?:e[-+]?\d+)?/g);
  let i=0, cmd, p=[0,0], contour;
  const contours=[];
  while(i<tokens.length) {
    if (/^[a-z]$/i.test(tokens[i])) cmd=tokens[i++];
    const upper=cmd.toUpperCase(), relative=cmd!==upper;
    if(upper==='Z') { contour.closed=true; p=contour.rawStart; cmd=undefined; continue; }
    const n={M:2,L:2,H:1,V:1,C:6,A:7}[upper];
    if(!n) throw new Error(`Unsupported command ${cmd}`);
    const v=tokens.slice(i,i+n).map(Number); i+=n;
    if(v.length!==n || v.some(x=>!Number.isFinite(x))) throw new Error('Bad path');
    const pt=(x,y)=>[x+(relative?p[0]:0),y+(relative?p[1]:0)];
    if(upper==='M') { p=pt(...v); contour={id:`${id}-${contours.length}`,start:norm(p),rawStart:p,segments:[],closed:false}; contours.push(contour); cmd=relative?'l':'L'; continue; }
    let s;
    if(upper==='C') s={kind:'cubic',c1:norm(pt(v[0],v[1])),c2:norm(pt(v[2],v[3])),to:norm(pt(v[4],v[5]))};
    else if(upper==='A') { if(v[2]!==0 || ![0,1].includes(v[3]) || ![0,1].includes(v[4])) throw new Error('Unsupported arc'); s={kind:'arc',radii:norm(v.slice(0,2)),largeArc:!!v[3],sweep:!!v[4],to:norm(pt(v[5],v[6]))}; }
    else s={kind:'line',to:norm(upper==='H'?[relative?p[0]+v[0]:v[0],p[1]]:upper==='V'?[p[0],relative?p[1]+v[0]:v[0]]:pt(...v))};
    contour.segments.push(s);
    // Retain full precision for relative SVG command accumulation.
    if(upper==='C') p=pt(v[4],v[5]); else if(upper==='A') p=pt(v[5],v[6]);
    else if(upper==='H') p=[relative?p[0]+v[0]:v[0],p[1]]; else if(upper==='V') p=[p[0],relative?p[1]+v[0]:v[0]]; else p=pt(...v);
  }
  return contours.map(({rawStart,...c})=>c);
}
const licenseNotice=readFileSync('node_modules/lucide-react/LICENSE','utf8');
const version=JSON.parse(readFileSync('node_modules/lucide-react/package.json')).version;
const icons=names.map(name=>{
  const source=readFileSync(`node_modules/lucide-react/dist/esm/icons/${name}.js`,'utf8');
  const node=Function(`return ${source.match(/const __iconNode = ([\s\S]*?);/)[1]}`)();
  const groups=node.map(([kind,a],i)=>{
    let d;
    if(kind==='path') d=a.d;
    else if(kind==='circle') { const x=+a.cx,y=+a.cy,r=+a.r; d=`M${x-r} ${y}a${r} ${r} 0 1 0 ${2*r} 0a${r} ${r} 0 1 0 ${-2*r} 0Z`; }
    else if(kind==='rect') {const x=+a.x,y=+a.y,w=+a.width,h=+a.height,rx=+(a.rx??0),ry=+(a.ry??rx); d=`M${x+rx} ${y}h${w-2*rx}a${rx} ${ry} 0 0 1 ${rx} ${ry}v${h-2*ry}a${rx} ${ry} 0 0 1 ${-rx} ${ry}h${2*rx-w}a${rx} ${ry} 0 0 1 ${-rx} ${-ry}v${2*ry-h}a${rx} ${ry} 0 0 1 ${rx} ${-ry}Z`; }
    else throw new Error(kind);
    return path(d,String(i));
  });
  const contours=groups.flat();
  return {id:name,aspectRatio:24 / 24,label:name==='house'?'Home':name.split('-').map(s=>s[0].toUpperCase()+s.slice(1)).join(' '),geometry:{kind:'vector',version:1,provenance:{library:'Lucide',version,icon:name,license:'ISC',licenseNotice},contours,fills:(regions[name]??[]).map(ids=>({contourIds:ids.flatMap(i=>groups[i].map(c=>c.id)),rule:'evenodd'})),strokes:contours.map(c=>c.id)}};
});
